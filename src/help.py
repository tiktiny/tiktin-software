class HelpDialog(QDialog):
    def __init__(self, parent, version=""):
        super().__init__(parent)
        self.setWindowTitle("טיקטין PDF A — הוראות הפעלה")
        self.setLayoutDirection(Qt.RightToLeft)
        self.setAttribute(Qt.WA_DeleteOnClose, True)
        lay = QVBoxLayout(self)
        lay.setContentsMargins(12, 12, 12, 10)
        tb = QTextBrowser()
        tb.setOpenLinks(False)
        tb.setStyleSheet("QTextBrowser{background:#ffffff;border:1px solid #cfd4db;}")
        tb.document().setDefaultStyleSheet("")
        tb.setHtml(f'<div dir="rtl">{HELP_HTML}</div>')
        tb.anchorClicked.connect(lambda url: tb.scrollToAnchor(url.fragment()))
        lay.addWidget(tb, 1)
        row = QHBoxLayout()
        v = QLabel(version)
        v.setStyleSheet("color:#7a828e;")
        row.addWidget(v)
        row.addStretch(1)
        close = QPushButton("סגירה")
        close.setObjectName("primaryBtn")
        close.clicked.connect(self.close)
        row.addWidget(close)
        lay.addLayout(row)
        scr = parent.screen().availableGeometry() if parent is not None and parent.screen() else None
        h = min(720, int(scr.height() * 0.85)) if scr else 680
        self.resize(780, h)
