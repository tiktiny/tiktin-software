class HelpDialog(QDialog):
    def __init__(self, parent, app_name, version, date):
        super().__init__(parent)
        self.setWindowTitle(f"הוראות הפעלה – {app_name}")
        self.setLayoutDirection(Qt.RightToLeft)
        self.resize(780, 680)
        lay = QVBoxLayout(self)
        tb = QTextBrowser()
        tb.setLayoutDirection(Qt.RightToLeft)
        tb.setOpenExternalLinks(False)
        tb.setStyleSheet("QTextBrowser { background: #ffffff; border: 1px solid #cdd2d1; padding: 10px; }")
        html = HELP_HTML.replace("{app}", app_name).replace("{ver}", version).replace("{date}", date)
        tb.setHtml(f'<div dir="rtl">{html}</div>')
        lay.addWidget(tb)
        row = QHBoxLayout()
        row.addStretch(1)
        b = QPushButton("סגירה")
        b.setObjectName("plainBtn")
        b.clicked.connect(self.accept)
        row.addWidget(b)
        lay.addLayout(row)
